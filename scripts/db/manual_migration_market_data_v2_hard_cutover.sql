SELECT pg_advisory_xact_lock(9021002);

CREATE EXTENSION IF NOT EXISTS pgcrypto;

DO $$
DECLARE
    missing_instruments bigint;
    invalid_rows bigint;
    open_rows bigint;
    invalid_source_times bigint;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'timescaledb') THEN
        RAISE EXCEPTION 'market_data_v2_preflight: timescaledb extension is required';
    END IF;
    IF to_regclass('public.market_candles_raw') IS NULL THEN
        RAISE EXCEPTION 'market_data_v2_preflight: public.market_candles_raw is missing';
    END IF;
    IF to_regclass('market.candle_versions') IS NOT NULL
       OR to_regclass('legacy_market_v1.market_candles_raw') IS NOT NULL THEN
        RAISE EXCEPTION
            'market_data_v2_preflight: partial canonical or archive state exists';
    END IF;

    SELECT count(*) INTO missing_instruments
    FROM public.market_candles_raw AS candle
    LEFT JOIN public.portal_instruments AS instrument
      ON instrument.id = candle.instrument_id
    WHERE instrument.id IS NULL
       OR NULLIF(btrim(instrument.datasource), '') IS NULL;
    IF missing_instruments > 0 THEN
        RAISE EXCEPTION
            'market_data_v2_preflight: % candle rows lack a canonical instrument/provider',
            missing_instruments;
    END IF;

    SELECT count(*) INTO invalid_rows
    FROM public.market_candles_raw
    WHERE close_time <= candle_time
       OR high < low
       OR high < open
       OR high < close
       OR low > open
       OR low > close
       OR volume < 0
       OR trade_count < 0
       OR timeframe_seconds <= 0;
    IF invalid_rows > 0 THEN
        RAISE EXCEPTION
            'market_data_v2_preflight: % malformed candle rows', invalid_rows;
    END IF;

    SELECT count(*) INTO open_rows
    FROM public.market_candles_raw
    WHERE NOT is_closed;
    IF open_rows > 0 THEN
        RAISE EXCEPTION
            'market_data_v2_preflight: % provisional candles cannot enter canonical storage',
            open_rows;
    END IF;

    SELECT count(*) INTO invalid_source_times
    FROM public.market_candles_raw
    WHERE source_time IS NOT NULL AND source_time < close_time;
    IF invalid_source_times > 0 THEN
        RAISE EXCEPTION
            'market_data_v2_preflight: % source timestamps precede candle close',
            invalid_source_times;
    END IF;
END;
$$;

