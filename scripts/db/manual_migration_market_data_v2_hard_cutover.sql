--
-- Run with backend, workers, and paper runtimes stopped. Take a schema-only and
-- data backup before execution. This migration intentionally creates no dual
-- writes, compatibility views, or runtime fallback path.

SELECT (
    to_regclass('legacy_market_v1.market_candles_raw') IS NOT NULL
    AND to_regclass('market.candle_versions') IS NOT NULL
    AND to_regclass('public.market_candles_raw') IS NULL
) AS market_data_v2_complete
\gset

\if :market_data_v2_complete
DO $$
BEGIN
    IF to_regclass('public.derivatives_market_state') IS NOT NULL
       OR to_regclass('public.portal_candle_closures') IS NOT NULL THEN
        RAISE EXCEPTION
            'market_data_v2_repeat_invalid: legacy active tables remain in public';
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM legacy_market_v1.migration_manifest
        WHERE migration_id = 'market_data_v2_hard_cutover'
          AND completed_at IS NOT NULL
    ) THEN
        RAISE EXCEPTION
            'market_data_v2_repeat_invalid: completed manifest is missing';
    END IF;
END;
$$;
\echo 'market_data_v2_hard_cutover already complete; verification passed'
SELECT *
FROM legacy_market_v1.migration_manifest
WHERE migration_id = 'market_data_v2_hard_cutover';
\quit
\endif

