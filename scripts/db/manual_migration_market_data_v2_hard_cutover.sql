WITH ordered AS (
    SELECT
        series.id AS series_id,
        candle.candle_time,
        candle.timeframe_seconds,
        lag(candle.candle_time) OVER (
            PARTITION BY series.id ORDER BY candle.candle_time
        ) AS previous_time
    FROM public.market_candles_raw AS candle
    JOIN market.series AS series
      ON series.instrument_id = candle.instrument_id
     AND series.timeframe_seconds = candle.timeframe_seconds
     AND series.fact_type = 'candle.ohlcv'
), gaps AS (
    SELECT
        series_id,
        previous_time + make_interval(secs => timeframe_seconds) AS start_time,
        candle_time AS end_time,
        GREATEST(
            floor(extract(epoch FROM (candle_time - previous_time)) / timeframe_seconds)::integer - 1,
            0
        ) AS missing_count
    FROM ordered
    WHERE previous_time IS NOT NULL
      AND candle_time - previous_time > make_interval(secs => timeframe_seconds)
), watermarks AS (
    SELECT series_id, max(market_commit_seq) AS max_commit_seq
    FROM market.candle_versions
    GROUP BY series_id
)
INSERT INTO market.gap_evidence (
    series_id, ingestion_run_id, start_time, end_time, classification,
    expected_count, observed_count, detected_as_of_commit_seq,
    evidence_hash, evidence
)
SELECT
    gap.series_id,
    candle.ingestion_run_id,
    gap.start_time,
    gap.end_time,
    'missing',
    gap.missing_count,
    0,
    watermark.max_commit_seq,
    pg_temp.sha256_text(
        gap.series_id::text || '|' || pg_temp.canonical_time(gap.start_time) ||
        '|' || pg_temp.canonical_time(gap.end_time) || '|missing'
    ),
    jsonb_build_object(
        'schema_version', 'market_gap_evidence.v1',
        'source', 'legacy_market_v1_continuity_scan',
        'limitation', 'internal gaps only; requested outer coverage was not recoverable'
    )
FROM gaps AS gap
JOIN watermarks AS watermark ON watermark.series_id = gap.series_id
JOIN LATERAL (
    SELECT ingestion_run_id
    FROM market.candle_versions
    WHERE series_id = gap.series_id
    ORDER BY candle_open_time
    LIMIT 1
) AS candle ON TRUE;

DO $$
DECLARE
    legacy_count bigint;
    canonical_count bigint;
    mismatch_count bigint;
BEGIN
    SELECT count(*) INTO legacy_count FROM public.market_candles_raw;
    SELECT count(*) INTO canonical_count FROM market.candle_versions WHERE revision = 1;
    IF canonical_count <> legacy_count THEN
        RAISE EXCEPTION
            'market_data_v2_reconcile: count mismatch legacy=% canonical=%',
            legacy_count, canonical_count;
    END IF;

    SELECT count(*) INTO mismatch_count
    FROM public.market_candles_raw AS legacy
    JOIN market.series AS series
      ON series.instrument_id = legacy.instrument_id
     AND series.timeframe_seconds = legacy.timeframe_seconds
     AND series.fact_type = 'candle.ohlcv'
    JOIN market.candle_versions AS canonical
      ON canonical.series_id = series.id
     AND canonical.candle_open_time = legacy.candle_time
     AND canonical.revision = 1
    WHERE canonical.candle_close_time IS DISTINCT FROM legacy.close_time
       OR canonical.open IS DISTINCT FROM legacy.open
       OR canonical.high IS DISTINCT FROM legacy.high
       OR canonical.low IS DISTINCT FROM legacy.low
       OR canonical.close IS DISTINCT FROM legacy.close
       OR canonical.volume IS DISTINCT FROM legacy.volume
       OR canonical.trade_count IS DISTINCT FROM legacy.trade_count
       OR canonical.source_published_at IS DISTINCT FROM legacy.source_time
       OR canonical.known_at IS DISTINCT FROM COALESCE(legacy.source_time, legacy.close_time)
       OR canonical.row_hash IS DISTINCT FROM pg_temp.candle_row_hash(
            legacy.candle_time,
            legacy.close_time,
            legacy.open,
            legacy.high,
            legacy.low,
            legacy.close,
            legacy.volume,
            legacy.trade_count,
            legacy.source_time,
            NULL,
            COALESCE(legacy.source_time, legacy.close_time),
            CASE
                WHEN legacy.source_time IS NOT NULL THEN 'legacy_source_time'
                ELSE 'legacy_interval_close_inferred'
            END
       );
    IF mismatch_count > 0 THEN
        RAISE EXCEPTION
            'market_data_v2_reconcile: % exact value/hash mismatches', mismatch_count;
    END IF;
END;
$$;

