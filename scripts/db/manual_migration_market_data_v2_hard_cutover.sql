CREATE FUNCTION pg_temp.sha256_text(payload text)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
AS $$
    SELECT encode(digest(convert_to(payload, 'UTF8'), 'sha256'), 'hex')
$$;

CREATE FUNCTION pg_temp.json_string(payload text)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
AS $$
    SELECT to_json(payload)::text
$$;

CREATE FUNCTION pg_temp.canonical_time(payload timestamptz)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
AS $$
    SELECT to_char(
        payload AT TIME ZONE 'UTC',
        'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'
    )
$$;

CREATE FUNCTION pg_temp.canonical_float(payload double precision)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
AS $$
    SELECT encode(
        float8send(CASE WHEN payload = 0 THEN 0::double precision ELSE payload END),
        'hex'
    )
$$;

CREATE FUNCTION pg_temp.source_identity_key(
    provider text,
    venue text,
    source_kind text,
    adapter_version text
)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
AS $$
    SELECT pg_temp.sha256_text(
        '{"adapter_version":' || pg_temp.json_string(adapter_version) ||
        ',"provider":' || pg_temp.json_string(lower(provider)) ||
        ',"source_kind":' || pg_temp.json_string(lower(source_kind)) ||
        ',"venue":' || pg_temp.json_string(lower(venue)) ||
        '}'
    )
$$;

CREATE FUNCTION pg_temp.series_identity_key(
    instrument_id text,
    fact_type text,
    timeframe_seconds integer,
    contract_version text
)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
AS $$
    SELECT pg_temp.sha256_text(
        '{"contract_version":' || pg_temp.json_string(contract_version) ||
        ',"fact_type":' || pg_temp.json_string(fact_type) ||
        ',"instrument_id":' || pg_temp.json_string(instrument_id) ||
        ',"schema_version":"market_series.v1"' ||
        ',"timeframe_seconds":' || timeframe_seconds::text ||
        '}'
    )
$$;

CREATE FUNCTION pg_temp.candle_row_hash(
    candle_open_time timestamptz,
    candle_close_time timestamptz,
    open_value double precision,
    high_value double precision,
    low_value double precision,
    close_value double precision,
    volume_value double precision,
    trade_count_value bigint,
    source_published_at_value timestamptz,
    received_at_value timestamptz,
    known_at_value timestamptz,
    known_at_method_value text
)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT pg_temp.sha256_text(
        '{"close":' || pg_temp.json_string(pg_temp.canonical_float(close_value)) ||
        ',"close_time":' || pg_temp.json_string(pg_temp.canonical_time(candle_close_time)) ||
        ',"high":' || pg_temp.json_string(pg_temp.canonical_float(high_value)) ||
        ',"known_at":' || pg_temp.json_string(pg_temp.canonical_time(known_at_value)) ||
        ',"known_at_method":' || pg_temp.json_string(known_at_method_value) ||
        ',"low":' || pg_temp.json_string(pg_temp.canonical_float(low_value)) ||
        ',"open":' || pg_temp.json_string(pg_temp.canonical_float(open_value)) ||
        ',"open_time":' || pg_temp.json_string(pg_temp.canonical_time(candle_open_time)) ||
        ',"received_at":' || COALESCE(
            pg_temp.json_string(pg_temp.canonical_time(received_at_value)), 'null'
        ) ||
        ',"schema_version":"candle.ohlcv.v1"' ||
        ',"source_published_at":' || COALESCE(
            pg_temp.json_string(pg_temp.canonical_time(source_published_at_value)), 'null'
        ) ||
        ',"trade_count":' || COALESCE(trade_count_value::text, 'null') ||
        ',"volume":' || COALESCE(
            pg_temp.json_string(pg_temp.canonical_float(volume_value)), 'null'
        ) ||
        '}'
    )
$$;

